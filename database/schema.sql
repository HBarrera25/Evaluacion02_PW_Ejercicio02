BEGIN;

CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL CHECK (LENGTH(TRIM(nombre)) > 0),
    saldo_mensual NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (saldo_mensual >= 0),
    presupuesto_diario NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (presupuesto_diario >= 0)
);

CREATE TABLE alimentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL CHECK (LENGTH(TRIM(nombre)) > 0),
    categoria VARCHAR(50) NOT NULL CHECK (LENGTH(TRIM(categoria)) > 0),
    precio NUMERIC(10, 2) NOT NULL CHECK (precio > 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

CREATE TABLE reservas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente VARCHAR(100) CHECK (nombre_cliente IS NULL OR LENGTH(TRIM(nombre_cliente)) >= 2),
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
    estado VARCHAR(15) NOT NULL DEFAULT 'activa'
        CHECK (estado IN ('activa', 'confirmada', 'expirada')),
    creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expira_en TIMESTAMPTZ NOT NULL,
    confirmada_en TIMESTAMPTZ,
    CHECK (expira_en > creada_en),
    CHECK (
        (estado = 'confirmada' AND confirmada_en IS NOT NULL
            AND confirmada_en >= creada_en AND confirmada_en < expira_en)
        OR (estado <> 'confirmada' AND confirmada_en IS NULL)
    )
);

CREATE UNIQUE INDEX una_reserva_activa_por_usuario
    ON reservas(usuario_id) WHERE estado = 'activa';

CREATE TABLE reserva_items (
    reserva_id INTEGER NOT NULL REFERENCES reservas(id),
    alimento_id INTEGER NOT NULL REFERENCES alimentos(id),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario > 0),
    PRIMARY KEY (reserva_id, alimento_id)
);

CREATE INDEX reservas_activas_por_vencimiento
    ON reservas(expira_en) WHERE estado = 'activa';

CREATE INDEX reservas_confirmadas_por_usuario
    ON reservas(usuario_id, confirmada_en) WHERE estado = 'confirmada';

ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS nombre_usuario VARCHAR(30);
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS password_hash TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_nombre_usuario_unico ON usuarios (nombre_usuario);
CREATE TABLE IF NOT EXISTS sesiones (
  token_hash CHAR(64) PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  expira_en TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS sesiones_expiracion ON sesiones(expira_en);

COMMIT;
